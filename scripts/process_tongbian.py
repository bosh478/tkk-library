def extract_content_by_line_range(source_path, start_line, length=500):
    """按行号范围提取内容"""
    try:
        with open(source_path, 'r', encoding='utf-8') as f:
            lines = f.readlines()

        if start_line > len(lines):
            return None

        end_line = min(start_line + length, len(lines))
        content = ''.join(lines[start_line:end_line])
        return content
    except Exception as e:
        print(f"  读取错误: {e}")
        return None

def generate_concept_filename(book_key, chapter_name):
    """生成 concept 文件名"""
    short_name = BOOKS[book_key]['title'].replace('统编教材·', '').replace('（', '_').replace('）', '_').replace('：', '_').replace(' ', '_')
    # 简化书名
    short_name = re.sub(r'[^\\w一-鿿_]', '', short_name)
    short_name = short_name[:30]  # 限制长度

    # 简化章节名
    chapter_short = chapter_name.replace(' ', '_').replace('（', '').replace('）', '')
    chapter_short = re.sub(r'[^\\w一-鿿]', '', chapter_short)
    chapter_short = chapter_short[:20]

    return f"concept_统编教材_{short_name}_{chapter_short}_2025年.md"

def process_book(book_key, book_info):
    """处理单本书籍"""
    source_path = SOURCES_DIR / book_key
    if not source_path.exists():
        print(f"  源文件不存在: {source_path}")
        return 0

    created_count = 0
    for chapter_name, start_line in book_info['chapters']:
        filename = generate_concept_filename(book_key, chapter_name)
        filepath = WIKI_DIR / filename

        # 检查是否已存在
        if filepath.exists():
            continue

        # 提取内容
        content = extract_content_by_line_range(source_path, start_line)

        # 生成 frontmatter
        frontmatter = f"""---
title: {book_info['title']}·{chapter_name}
type: concept
created: 2026-04-22
updated: 2026-04-22
tags: {book_info['tags']}
source: [["《统编教材》{book_info['title'].replace('统编教材·', '')}"]]
---

# {book_info['title']}·{chapter_name}

## 章节概述

本章节内容源自《统编教材》{book_info['title']}。

"""

        if content:
            frontmatter += "## 章节内容\n\n"
            # 清理内容（去除表格等复杂格式）
            clean_content = re.sub(r'<table>.*?</table>', '', content, flags=re.DOTALL)
            clean_content = re.sub(r'续表', '', clean_content)
            frontmatter += clean_content[:8000]  # 限制总长度
        else:
            frontmatter += "\n\n> 内容待从源文件中提取补充。\n"

        try:
            filepath.write_text(frontmatter, encoding='utf-8')
            created_count += 1
            print(f"  创建: {filename}")
        except Exception as e:
            print(f"  写入错误 {filename}: {e}")

    return created_count

def main():
    """主函数"""
    print(f"开始处理《统编教材》系列书籍 ({len(BOOKS)} 本)")
    print("=" * 50)

    total_created = 0

    for book_key, book_info in BOOKS.items():
        print(f"\n处理: {book_key}")
        created = process_book(book_key, book_info)
        total_created += created
        print(f"  本书新增: {created} 个 concept 页面")

    print("\n" + "=" * 50)
    print(f"处理完成: 共创建 {total_created} 个 concept 页面")

if __name__ == "__main__":
    main()
