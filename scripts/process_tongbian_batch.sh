    ["《统编教材》立案工作实务2.md"]="立案工作实务"
    ["《统编教材》行政审判实务8.md"]="行政审判实务"
)

echo "开始处理《统编教材》系列书籍..."
echo "共 ${#BOOKS[@]} 本书"

total_created=0
total_skipped=0

for source_file in "${!BOOKS[@]}"; do
    short_name="${BOOKS[$source_file]}"
    source_path="$SOURCES_DIR/$source_file"

    if [ ! -f "$source_path" ]; then
        echo "文件不存在: $source_path"
        continue
    fi

    echo "处理: $source_file"

    # 获取文件行数
    lines=$(wc -l < "$source_path")
    echo "  总行数: $lines"

    # 统计该书已有的细化 concept 页面数量
    existing_count=$(ls "$WIKI_DIR"/concept_统编教材_${short_name}_*.md 2>/dev/null | wc -l)
    echo "  已有细化页面: $existing_count"
done

echo ""
echo "处理完成"
