    ["《统编教材》刑事审判实务上册3.md"]="刑事审判实务_上册"
    ["《统编教材》刑事审判实务下册3.md"]="刑事审判实务_下册"
    ["《统编教材》审判监督实务上册9.md"]="审判监督实务_上册"
    ["《统编教材》审判监督实务下册9.md"]="审判监督实务_下册"
    ["《统编教材》审判管理实务12.md"]="审判管理实务"
    ["《统编教材》未成年人审判实务13.md"]="未成年人审判实务"
    ["《统编教材》民商事审判实务4第1册-总则、物权、建设用地.md"]="民商事审判实务_第1册_总则物权建设用地"
    ["《统编教材》民商事审判实务4第2册-担保、合同.md"]="民商事审判实务_第2册_担保合同"
    ["《统编教材》民商事审判实务4第3册-房屋、借贷、建设工程、物业、劳动争议.md"]="民商事审判实务_第3册_房屋借贷建设工程物业劳动"
    ["《统编教材》民商事审判实务4第4册-人格权、婚姻家庭、继承、侵权、消费者、审判程序.md"]="民商事审判实务_第4册_人格权婚姻家庭继承侵权消费者"
    ["《统编教材》民商事审判实务4第5册-公司、破产.md"]="民商事审判实务_第5册_公司破产"
    ["《统编教材》民商事审判实务4第6册-保险、票据、信托、证券、期货.md"]="民商事审判实务_第6册_保险票据信托证券期货"
    ["《统编教材》法院审委会手册 刑事卷 2025年.md"]="法院审委会手册_刑事卷"
    ["《统编教材》法院审委会手册 民商事卷 2025年.md"]="法院审委会手册_民商事卷"
    ["《统编教材》法院审委会手册 行政卷 2025年.md"]="法院审委会手册_行政卷"
    ["《统编教材》涉外商事海事审判实务和国际司法协助.md"]="涉外商事海事审判实务"
