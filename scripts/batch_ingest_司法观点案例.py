def create_wiki_page(meta):
    """Create a wiki summary page from metadata."""
    tags_str = ", ".join(meta["tags"])
    key_points_str = "\n".join([f"- {p}" for p in meta["key_points"]])
    faq_str = "\n".join([f"> 问：{q}\n> 答：{a}\n" for q, a in meta["faq"]])

    content = f"""---
title: "{meta['title']}"
type: summary
created: 2026-05-27
updated: 2026-05-27
tags: [{tags_str}]
source: "sources/司法观点、案例/{meta['source']}"
category: {meta['category']}
---

## 📋 文档概览

| 字段 | 内容 |
|------|------|
| 来源 | [[{meta['source']}]] |
| 类型 | {meta['doc_type']} |
| 关键词 | {' / '.join(meta['tags'][:3])} |
| 核心要点 | {meta['overview'][:80]}... |

## ❓ 常见问题

{faq_str}
## 核心内容

### 文档概览

{meta['overview']}

### 关键要点

{key_points_str}
"""
    return content

def main():
    """Main function to create all wiki summary pages."""
    # Ensure target directory exists
    TARGET_DIR.mkdir(parents=True, exist_ok=True)

    created = 0
    skipped = 0
    errors = []

    for meta in FILES_META:
        # Generate filename from source
        source_name = meta["source"].replace(".md", "")
        # Clean up filename for wiki page
        filename = f"summary_司法观点_{source_name[:60]}.md"
        # Remove invalid characters
        filename = filename.replace("（", "").replace("）", "").replace("《", "").replace("》", "").replace("：", "").replace("、", "_")

        target_path = TARGET_DIR / filename

        # Check if file already exists
        if target_path.exists():
            print(f"[SKIP] {filename} already exists")
            skipped += 1
            continue

        try:
            content = create_wiki_page(meta)
            target_path.write_text(content, encoding="utf-8")
            print(f"[OK] Created {filename}")
            created += 1
        except Exception as e:
            print(f"[ERROR] Failed to create {filename}: {e}")
            errors.append((filename, str(e)))

    print(f"\n=== Summary ===")
    print(f"Created: {created}")
    print(f"Skipped: {skipped}")
    print(f"Errors: {len(errors)}")
    if errors:
        print("Error details:")
        for fname, err in errors:
            print(f"  - {fname}: {err}")

if __name__ == "__main__":
    main()
