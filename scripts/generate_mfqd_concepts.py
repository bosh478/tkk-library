def main():
    TARGET_DIR.mkdir(parents=True, exist_ok=True)

    created = []
    for source_file, concept_name, page_range, tags, category in FILE_MAPPING:
        target_name = f"concept_民法典适用大全_{concept_name.replace('·', '_')}.md"
        target_path = TARGET_DIR / target_name

        content = generate_content(source_file, concept_name, page_range, tags, category)

        with open(target_path, 'w', encoding='utf-8') as f:
            f.write(content)

        created.append(target_name)
        print(f"Created: {target_name}")

    print(f"\nTotal created: {len(created)}")


if __name__ == "__main__":
    main()