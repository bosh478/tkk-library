    line_refs = {}
    if page_range:
        line_refs[source_file] = [1, 50]
    else:
        line_refs[source_file] = [1, 50]

    # Build related section
    related = RELATED_LINKS.get(concept_name, ["[[concept_中华人民共和国民法典]]"])
    related_str = "\n  - ".join(related)

